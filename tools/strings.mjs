#!/usr/bin/env node
// Localisation generator: src/PurgeWindows/Localization/strings.json is the source of
// truth. It writes the typed accessors (S.g.cs) and the .resx catalogues.
//
//   node tools/strings.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const locDir = path.join(root, 'src', 'PurgeWindows', 'Localization');
const manifest = JSON.parse(fs.readFileSync(path.join(locDir, 'strings.json'), 'utf8'));
const strings = manifest.strings;

const xmlEscape = (s) => s
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

const resx = (entries, lang) => `<?xml version="1.0" encoding="utf-8"?>
<root>
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
${entries.map((e) => `  <data name="${e.key}" xml:space="preserve">
    <value>${xmlEscape(lang === 'ru' ? e.ru : e.en)}</value>
  </data>`).join('\n')}
</root>
`;

// Entries without a translation are left out of that language's catalogue, so
// the runtime falls back to the English text (see Loc.cs). Never invent a
// translation here; translators fill the gaps in strings.json.
const untranslated = strings.filter((e) => !e.ru).map((e) => e.key);

fs.writeFileSync(path.join(locDir, 'Strings.resx'), resx(strings, 'en'));
fs.writeFileSync(path.join(locDir, 'Strings.ru.resx'), resx(strings.filter((e) => e.ru), 'ru'));

const properties = strings
  .map((e) => `    /// <summary>${e.en.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/\*\//g, '* /')}</summary>\n    public static string ${e.key} => Loc.Get("${e.key}");`)
  .join('\n\n');

fs.writeFileSync(path.join(locDir, 'S.g.cs'), `// <auto-generated>
// Generated from src/PurgeWindows/Localization/strings.json by tools/strings.mjs.
// Add a string there, not here.
// </auto-generated>
namespace PurgeWindows.Localization;

/// <summary>Typed access to every user-facing string. Values follow the system language.</summary>
public static class S
{
${properties}
}
`);

console.log(`strings.json: ${strings.length} strings; S.g.cs and both .resx files written`);
if (untranslated.length > 0) console.log(`untranslated (ru falls back to en): ${untranslated.join(', ')}`);
